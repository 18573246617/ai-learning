CREATE TABLE
  tasks3 (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    user_id2 BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    user_id3 BIGINT REFERENCES users (id) ON DELETE CASCADE NOT NULL,
  );

-- CHECK练习
CREATE TABLE
  tasks4 (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users (id) ON DELETE CASCADE,
    title TEXT CHECK (length (title) > 0), -- 标题长度大于0
    title1 TEXT CHECK (length (title1) BETWEEN 1 AND 200), -- 标题长度 1~200
    title2 TEXT NOT NULL CHECK (char_length(title2) BETWEEN 1 AND 200), -- 标题长度 1~200
    status TEXT CHECK (status in ('a', 'b', 'c')) -- 状态必须是 a, b, c 中的一个
    discount BIGINT CHECK (
      discount >= 0
      AND discount <= 100
    ),
    title3 TEXT NOT NULL,
    email TEXT NOT NULL,
    CHECK (email LIKE '%_@_%._%'),
    CHECK (trim(email) <> ''), --<> 相当于 !=
    CHECK (
      length (title) BETWEEN 1 AND 200
      OR title1 NOT NULL
    ),
  )
