-- 2.约束 
PRIMARY KEY -- 主键约束，唯一，非空
NOT NULL -- 约束，非空
UNIQUE -- 唯一约束，唯一
DEFAULT -- 默认值约束，默认值
FOREIGN KEY -- 外键约束，引用其他表的主键
CHECK -- 检查约束，检查值是否符合要求
CREATE TABLE
  users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id2 BIGINT NOT NULL UNIQUE,
    username VARCHAR(20) NOT NULL,
    password_hash text NOT NULL
  );

CREATE TABLE
  tasks (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE -- ← 单独声明
  );

CREATE TABLE
  tasks1 (
